function isNoticeCase(serviceId, queryIndex) {
  if (serviceId === "notice-litigation") return true;
  const svc = SERVICES.find((s) => s.id === serviceId);
  const qObj = svc?.queries[queryIndex];
  const hi = (qObj?.hi || "").toLowerCase();
  return (
    hi.includes("नोटिस") ||
    hi.includes("अपील") ||
    hi.includes("डिमांड") ||
    hi.includes("विवाद") ||
    hi.includes("रद्द")
  );
}

function getRequiredDocuments(serviceId, entityId, queryIndex, forceNotice = false, lang = "hi") {
  const matrix = DOCUMENT_MATRIX[serviceId] || DOCUMENT_MATRIX.gst;
  const base = matrix.all || [];
  const entitySpecific = matrix[entityId] || [];
  const extra = [];

  const svc = SERVICES.find((s) => s.id === serviceId);
  const qHi = svc?.queries[queryIndex]?.hi || "";

  if ((forceNotice || isNoticeCase(serviceId, queryIndex)) && matrix.notice) {
    extra.push(...matrix.notice);
  }
  if (serviceId === "audit" && qHi.includes("टैक्स ऑडिट") && matrix.notice) {
    extra.push(...matrix.notice);
  }

  const seen = new Set();
  const result = [];
  [...base, ...entitySpecific, ...extra].forEach((item) => {
    const label = item[lang] || item.hi;
    if (!seen.has(label)) {
      seen.add(label);
      result.push(label);
    }
  });
  return result;
}

